/**
 * The internal panel's sections (doc 09, 2-11) and the permission that opens each (doc 04).
 * A section the account cannot use is not shown; the API refuses it anyway (rule 12).
 * Each has its group, glyph and color on the service desk and in the menu (owner 1405/08/10).
 */
export interface AdminSection {
  readonly href: string;
  readonly label: string;
  /** The bottom bar's label (owner 1405/08/11): at most 12 letters, never cut. */
  readonly shortLabel: string;
  readonly group: AdminGroup;
  readonly glyph: GlyphName;
  readonly isNew?: boolean;
  readonly description: string;
  /** Any one of these opens the section; none: every signed-in account. */
  readonly anyOf: readonly string[];
}

